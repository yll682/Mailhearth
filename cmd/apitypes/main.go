// Command apitypes writes web/src/lib/api-types.ts from the Go types the
// HTTP API returns. Run it after changing a response type:
//
//	go run ./cmd/apitypes
//
// The test in this package fails when the committed file is out of date.
package main

import (
	"flag"
	"fmt"
	"os"
	"reflect"

	"mailhearth/internal/apitypes"
	"mailhearth/internal/core"
	"mailhearth/internal/httpapi"
	"mailhearth/internal/mailproto/mailops"
	"mailhearth/internal/model"
	"mailhearth/internal/provider"
)

const header = `// Code generated by go run ./cmd/apitypes; DO NOT EDIT.
// Source: the Go response types of the HTTP API.
`

// generate lists every response root; referenced types follow.
func generate() (string, error) {
	g := apitypes.New(
		apitypes.Enum{Type: reflect.TypeOf(provider.ProviderKind("")), Values: []string{string(provider.Purelymail), string(provider.Migadu), string(provider.Manual)}},
		apitypes.Enum{Type: reflect.TypeOf(provider.ResourcePurpose("")), Values: []string{
			string(provider.PurposeDomain), string(provider.PurposeMailbox), string(provider.PurposeRouting),
			string(provider.PurposeForwarding), string(provider.PurposeSenderIdentity), string(provider.PurposeLoginCredential),
		}},
	)
	return g.Add(
		// Session and setup
		httpapi.MeResponse{}, core.SetupStatus{}, core.Overview{},
		// Organisation, members, roles, audit
		model.Organization{}, model.Member{}, model.Role{}, model.AuditEntry{}, httpapi.DirectoryEntry{},
		// Connections, domains, discovery, billing
		core.ConnectionView{}, provider.Capability{}, model.DomainBinding{}, model.Domain{},
		provider.DiscoverySnapshotResource{}, core.ConnectionBillingView{}, httpapi.ResourceOptions{},
		// Mailboxes, routing and operations
		model.Mailbox{}, core.AccessibleMailbox{}, model.MailboxAccess{}, model.Identity{}, core.FolderMappingView{},
		model.MailboxForwarding{}, model.Address{}, model.Group{}, core.OperationView{},
		// Mail
		mailops.Folder{}, httpapi.MessageListResponse{}, httpapi.MessageResponse{}, core.SubmissionView{},
		core.Contact{}, httpapi.UploadInfo{},
	).Source(header)
}

func main() {
	out := flag.String("o", "web/src/lib/api-types.ts", "output file")
	flag.Parse()
	src, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "apitypes:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "apitypes:", err)
		os.Exit(1)
	}
}
